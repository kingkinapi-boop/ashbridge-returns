export const glName = (n) => (GL[n] ? GL[n].name : `? ${n}`);
export function gifiFor(gl, netCents) {
  const e = GL[gl];
  if (!e) throw new Error('unknown GL ' + gl);
  if (e.gifiCr || e.gifiDr) return netCents < 0 ? e.gifiCr : e.gifiDr;
  return e.gifi;
}
export const isPL = (gl) => +gl >= 4000;
