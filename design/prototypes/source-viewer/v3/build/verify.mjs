// The verify script of the source viewer prototype v3 (design family checks 6 to 9, plan/cards/families/design.md).
// Serves design/ over http on a random port (never file://), drives headless Chromium, and writes verify-result.json next to this file.
// Run it through the laptop wrapper:  node tools/heavy.mjs -- node design/prototypes/source-viewer/v3/build/verify.mjs
// SV_ONLY=lint,axe runs some sections; with SV_ONLY the result goes to SV_OUT (or is only printed). PW_NM=<folder holding node_modules>
// points at Playwright and axe-core when they are not above this folder. Sections, in order:
//   lint     check 6 (retired terms, removed clauses) and check 7 and 9 on the files
//   axe      check 8: axe on every state at both sizes, contrast "incomplete" counted as a failure, and at 320 px
//   budgets  check 8: the budget counter at 1366 x 650 and 1093 x 525 (loads, clicks, keys, page area, text size, rows beside the pane)
//   reflow   check 8: 320 px reflow, one view at a time, the pane beside the list at a wider size
//   keys     the keys of D01's one list; keyboard: the Tab walk, focus style, order, targets
//   tasks, window, url, done, search   the brief's task scripts, the second window, the URL, done rows and Undo, header search
//   states, popup, actions, rules, controls   shared checks V1 to V8 of design/verify/rules.mjs
//   dom, counts, strings, links   the rendered DOM, counts that agree, one figure one string, every link
import fs from 'node:fs'
import path from 'node:path'
import { init, setSection, out, HERE } from './verify-lib.mjs'
import { sections as sStatic } from './verify-static.mjs'
import { sections as sRender } from './verify-render.mjs'
import { sections as sKeys } from './verify-keys.mjs'
import { sections as sFlows } from './verify-flows.mjs'
import { sections as sShared } from './verify-shared.mjs'

const ALL = { ...sStatic, ...sRender, ...sKeys, ...sFlows, ...sShared }
const ORDER = ['lint', 'axe', 'budgets', 'reflow', 'keys', 'keyboard', 'tasks', 'window', 'url', 'done', 'search', 'states', 'popup', 'actions', 'rules', 'controls', 'dom', 'counts', 'strings', 'links']
const only = process.env.SV_ONLY ? process.env.SV_ONLY.split(',').map((s) => s.trim()).filter(Boolean) : null
for (const o of only || []) if (!ALL[o]) { console.log('unknown section', o); process.exit(2) }

const T = await init()
const t0 = Date.now()
for (const name of ORDER) {
  if (only && !only.includes(name)) continue
  setSection(name)
  const s0 = Date.now(), n0 = out.checks.length
  try { await ALL[name](T) } catch (e) { T.ck(`section ${name} ran to the end`, false, String(e.stack || e).split('\n').slice(0, 5).join(' | ')) }
  const mine = out.checks.slice(n0)
  const failed = mine.filter((c) => !c.ok).length
  out.sections[name] = { checks: mine.length, failed, seconds: Math.round((Date.now() - s0) / 1000) }
  console.log(`section ${name}: ${mine.length} checks, ${failed} failed, ${out.sections[name].seconds} s`)
}
await T.close()

const failed = out.checks.filter((c) => !c.ok)
const result = {
  note: 'Generated by build/verify.mjs; made-up test-world data only; headless Chromium over http',
  ranSections: Object.keys(out.sections), seconds: Math.round((Date.now() - t0) / 1000),
  totals: { checks: out.checks.length, passed: out.checks.length - failed.length, failed: failed.length },
  sections: out.sections, sharedRuleTally: out.sharedTally || {}, budgetSummary: out.budgetSummary || null, tasks: out.tasks, keyboard: out.keyboard, reflow: out.reflow, window: out.window,
  axe: { pages: out.axe.length, withViolations: out.axe.filter((a) => a.violations.length).length, withIncomplete: out.axe.filter((a) => a.incomplete.length).length, resolvedByCalculation: out.axe.reduce((n, a) => n + (a.resolvedByCalculation || 0), 0), list: out.axe.map((a) => a.label) },
  budgets: out.budgets, lint: out.lint,
  failures: failed.map((c) => ({ section: c.section, name: c.name, detail: c.detail })),
  checks: out.checks.map((c) => ({ s: c.section, n: c.name, ok: c.ok, ...(c.ok ? {} : { d: c.detail }) })),
}
const file = only ? process.env.SV_OUT : (process.env.SV_OUT || path.join(HERE, 'verify-result.json'))
if (file) { fs.writeFileSync(file, JSON.stringify(result, null, 1) + '\n'); console.log('wrote', file) }
console.log(`verify: ${result.totals.passed} of ${result.totals.checks} checks pass, ${failed.length} fail, ${result.seconds} s`)
for (const f of failed.slice(0, 40)) console.log(' FAIL', `[${f.section}]`, f.name, '|', String(f.detail).slice(0, 200))
process.exit(failed.length ? 1 : 0)
